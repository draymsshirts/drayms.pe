// FUNCIONALIDAD DE TALLAS Y CARRITO
function seleccionarTalla(btn, size) {
  document.querySelectorAll('.size-btn').forEach(b => b.classList.remove('active-size'));
  btn.classList.add('active-size');
  selectedSize = size;
}

updateCartCounter();

function agregarAlCarrito() {
  if (!selectedSize || !selectedFit) {
    alert("Selecciona talla y corte");
    return;
  }

  const cart = JSON.parse(localStorage.getItem('drayms_cart') || '[]');

  cart.push({
    id: product.id,
    name: product.name,
    price: product.price,
    size: selectedSize,
    fit: selectedFit,
    image: mainImage
  });

  localStorage.setItem('drayms_cart', JSON.stringify(cart));

  localStorage.setItem('productPage', window.location.href);
  updateCartCounter();
  alert("Producto añadido 🔥");
}

// LOGICA VISUAL ORIGINAL
function cambiarImagen(src) {
  const mainImg = document.getElementById('main-img');
  if (mainImg) mainImg.src = src;

  mainImage = src; // 🔥 ESTO GUARDA LA IMAGEN CORRECTA
}

function toggleGuideAccordion() {
  const content = document.getElementById('guide-accordion-content');
  const icon = document.getElementById('guide-toggle-icon');
  content.classList.toggle('hidden');
  icon.textContent = content.classList.contains('hidden') ? '+' : '−';
}

function cambiarGuia(tipo) {
  selectedFit = tipo; // 🔥 GUARDAMOS EL FIT
  const tableBody = document.getElementById('guide-table-body');
  document.querySelectorAll('.guide-btn').forEach(btn => btn.classList.remove('active-guide'));
  document.getElementById(`btn-${tipo}`).classList.add('active-guide');
  const selectedGuide = product.guides[tipo];
  tableBody.innerHTML = selectedGuide.map((row) => `<tr class="border-t border-white/10"><td class="px-4 py-3">${row.size}</td><td class="px-4 py-3 text-zinc-300">${row.width}</td><td class="px-4 py-3 text-zinc-300">${row.length}</td><td class="px-4 py-3 text-zinc-300">${row.manga}</td></tr>`).join('');
}

function toggleAccordion(name) {
  const content = document.getElementById(`${name}-content`);
  const icon = document.getElementById(`${name}-icon`);
  content.classList.toggle('hidden');
  icon.textContent = content.classList.contains('hidden') ? '+' : '−';
}

// LOGICA DE MODAL ZOOM ORIGINAL
let zoomLevel = 0.75;
function abrirModalImagen(src) {
  const modal = document.getElementById('image-modal');
  const modalImg = document.getElementById('modal-img');
  const modalScroll = document.getElementById('image-modal-scroll');
  zoomLevel = 0.75;
  modalImg.src = src;
  modalImg.style.transform = `scale(${zoomLevel})`;
  modal.classList.remove('hidden');
  modalImg.onclick = function (e) {
    e.stopPropagation();
    if (zoomLevel < 1.6) zoomLevel = 1.6; else zoomLevel = 0.75;
    modalImg.style.transform = `scale(${zoomLevel})`;
  };
}

function cerrarModalImagen(e) {
  if (e.target.id === 'modal-img') return;
  document.getElementById('image-modal').classList.add('hidden');
}

